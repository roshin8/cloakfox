def build_owned_ruby_font():
    """Reproducible, self-owned metric oracle; B advances 500 or 900 units."""
    builder = FontBuilder(1000, isTTF=True)
    order = ['.notdef', 'space', 'base', 'rubyAlternate']
    builder.setupGlyphOrder(order)
    builder.setupCharacterMap({32:'space', 66:'base'})
    glyphs = {}
    for name, width in [('.notdef',400),('space',0),('base',400),('rubyAlternate',800)]:
        pen = TTGlyphPen(None)
        if width:
            pen.moveTo((50,0));pen.lineTo((50,700));pen.lineTo((width+50,700));pen.lineTo((width+50,0));pen.closePath()
        glyphs[name] = pen.glyph()
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({'.notdef':(500,50),'space':(250,0),'base':(500,50),'rubyAlternate':(900,50)})
    builder.setupHorizontalHeader(ascent=800, descent=-200, lineGap=0)
    builder.setupNameTable({'familyName':'Cloakfox Ruby Fixture','styleName':'Regular',
        'uniqueFontIdentifier':'CloakfoxRubyFixture-Regular-1','fullName':'Cloakfox Ruby Fixture Regular',
        'psName':'CloakfoxRubyFixture-Regular','version':'Version 1.0'})
    builder.setupOS2(sTypoAscender=800,sTypoDescender=-200,sTypoLineGap=0,usWinAscent=800,usWinDescent=200)
    builder.setupPost()
    builder.setupMaxp()
    addOpenTypeFeaturesFromString(builder.font, 'languagesystem DFLT dflt; languagesystem latn dflt; feature ruby { sub base by rubyAlternate; } ruby;')
    # Fixed OpenType timestamps make the generated bytes and report hash stable.
    builder.font['head'].created = builder.font['head'].modified = 2082844800
    builder.font.recalcTimestamp = False
    stream = io.BytesIO()
    builder.font.save(stream, reorderTables=True)
    data = stream.getvalue()
    font = TTFont(io.BytesIO(data))
    assert font['head'].unitsPerEm == 1000
    assert font['cmap'].getBestCmap()[66] == 'base'
    assert font['hmtx']['base'][0] == 500 and font['hmtx']['rubyAlternate'][0] == 900
    records = font['GSUB'].table.FeatureList.FeatureRecord
    feature = next(record.Feature for record in records if record.FeatureTag == 'ruby')
    lookup = font['GSUB'].table.LookupList.Lookup[feature.LookupListIndex[0]]
    assert lookup.SubTable[0].mapping['base'] == 'rubyAlternate'
    return data


def exact_color_mask(image, color):
    """Exact RGB equality using bounded native image bands, not pixel tuples."""
    masks = [band.point(lambda value, target=target: 255 if value == target else 0, '1')
             for band, target in zip(image.split(), color)]
    return ImageChops.logical_and(ImageChops.logical_and(masks[0], masks[1]), masks[2])


