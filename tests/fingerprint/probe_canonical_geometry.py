class Handler(BaseHTTPRequestHandler):
    font_bytes = b''
    def do_GET(self):
        is_font = self.path.split('?',1)[0] == '/owned-ruby.ttf'
        data = self.font_bytes if is_font else FIXTURE
        self.send_response(200)
        self.send_header('Content-Type', 'font/ttf' if is_font else 'text/html; charset=utf-8')
        self.send_header('Content-Length', str(len(data)))
        self.end_headers()
        self.wfile.write(data)
    def log_message(self, *_):
        pass


