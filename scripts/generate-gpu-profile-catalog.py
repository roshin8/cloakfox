#!/usr/bin/env python3
"""Generate native/privileged catalog representations; --check detects drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = ('texture','vertexUniforms','fragmentUniforms','vertexAttribs','combinedTexUnits','vertexTexUnits','fragmentTexUnits','vertexOutputs','fragmentInputs','texture3d','arrayLayers','uniformBufferBindings','drawBuffers','bufferBytes','storageBytes')


def render(data):
    if data.get('version') != 2 or data.get('kind') != 'canonical-executable-cohorts':
        raise ValueError('Unsupported catalog')
    profiles = data['profiles']; requirements = data['requirements']
    if not isinstance(profiles,list) or not 1 <= len(profiles) <= 255:
        raise ValueError('Invalid profile count')
    seen=set()
    for p in profiles:
        if set(p) != {'id','name','familyMask',*FIELDS} or type(p['id']) is not int or not 1 <= p['id'] <= 255 or p['id'] in seen:
            raise ValueError('Invalid/duplicate profile ID or fields')
        seen.add(p['id'])
        if not isinstance(p['name'],str) or not p['name'] or not p['name'].replace('-','').isalnum(): raise ValueError('Invalid profile name')
        if type(p['familyMask']) is not int or not 1 <= p['familyMask'] <= 15: raise ValueError('Invalid family mask')
        if any(type(p[k]) is not int or not 1 <= p[k] <= 0xffffffff for k in FIELDS): raise ValueError('Invalid capacity')
        if p['texture'] & (p['texture']-1) or p['texture'] < 2048: raise ValueError('Texture capacity must be a supported power-of-two cohort')
        if p['vertexUniforms']<256 or p['fragmentUniforms']<224 or p['vertexAttribs']<16 or p['vertexOutputs']<16 or p['fragmentInputs']<15: raise ValueError('Below WebGL2 resource minima')
        if p['vertexTexUnits']+p['fragmentTexUnits']>p['combinedTexUnits'] or p['drawBuffers']<4 or p['texture3d']<256 or p['arrayLayers']<256 or p['uniformBufferBindings']<24: raise ValueError('Incoherent resource tuple')
        if p['bufferBytes'] < 256*1024**2 or p['storageBytes'] < 128*1024**2 or p['storageBytes']>p['bufferBytes']: raise ValueError('Below WebGPU core defaults or invalid binding size')
    if not isinstance(requirements,list) or len(requirements)>64: raise ValueError('Invalid requirement table')
    seen=set()
    for r in requirements:
        if set(r)-{'pname','field','components','multiplier','webgl2Only'} or type(r['pname']) is not int or r['pname'] in seen or r['field'] not in FIELDS: raise ValueError('Invalid requirement')
        seen.add(r['pname'])
        if any(p[r['field']]*r.get('multiplier',1)>0xffffffff for p in profiles): raise ValueError('Requirement capacity overflow')
        if type(r.get('components',1)) is not int or type(r.get('multiplier',1)) is not int or r.get('components',1) not in (1,2) or r.get('multiplier',1) not in (1,4) or type(r.get('webgl2Only',False)) is not bool: raise ValueError('Invalid requirement shape')
    js='/* Generated by scripts/generate-gpu-profile-catalog.py; edit gpu-profile-catalog.json. */\n'
    js+='export const GPU_PROFILE_CATALOG_VERSION = 2;\n'
    js+='export const GPU_PROFILE_CATALOG = Object.freeze('+json.dumps(profiles,separators=(',',':'))+'.map(Object.freeze));\n'
    js+='export const GPU_PROFILE_REQUIREMENTS = Object.freeze('+json.dumps(requirements,separators=(',',':'))+'.map(Object.freeze));\n'
    cpp='/* Generated by scripts/generate-gpu-profile-catalog.py; edit gpu-profile-catalog.json. */\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace CloakfoxGPUCatalog {\n'
    cpp+='struct Limits { uint32_t id, familyMask; '+''.join('uint32_t '+k+'; ' for k in FIELDS)+'};\n'
    cpp+='inline constexpr Limits kProfiles[] = {\n'+''.join('  {'+','.join(str(p[k]) for k in ('id','familyMask',*FIELDS))+'},\n' for p in profiles)+'};\n'
    cpp+='struct Requirement { uint32_t pname, capacity, components; bool webgl2Only; };\n'
    cpp+='inline std::array<Requirement,'+str(len(requirements))+'> Requirements(const Limits& p) { return {{\n'
    cpp+=''.join('  {'+str(r['pname'])+',p.'+r['field']+'*'+str(r.get('multiplier',1))+','+str(r.get('components',1))+','+str(r.get('webgl2Only',False)).lower()+'},\n' for r in requirements)+'}}; }\n}\n'
    return js,cpp


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs=render(json.loads((ROOT/'additions/cloakcfg/gpu-profile-catalog.json').read_text()))
    paths=[ROOT/'additions/browser/components/cloakfox/CloakfoxGPUCatalog.sys.mjs',ROOT/'additions/cloakcfg/CloakfoxGPUCatalog.hpp']
    for path,content in zip(paths,outputs):
        if args.check:
            if not path.exists() or path.read_text()!=content: raise SystemExit('Generated catalog drift: '+str(path))
        else:path.write_text(content)
if __name__=='__main__':main()
