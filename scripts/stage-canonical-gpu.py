#!/usr/bin/env python3
"""Verify the complete pinned renderer before staging Gecko install resources."""
import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import tempfile


def stage(bundle, target):
    spec = importlib.util.spec_from_file_location('canonical_gpu_build', Path(__file__).with_name('build-canonical-gpu.py'))
    build = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(build)
    manifest = build.verify_integrity_manifest(bundle)
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.canonical-gpu-', dir=target.parent) as temporary:
        staged = Path(temporary) / 'resources'
        staged.mkdir()
        groups = {}
        for relative in sorted([*manifest['files'], 'manifest.json'], key=str.casefold):
            source = bundle / relative
            destination = staged / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
            groups.setdefault(Path(relative).parent.parts, []).append(relative)
        build.verify_integrity_manifest(staged)
        lines = ['# Generated by stage-canonical-gpu.py; verified manifest files only.']
        for parents, files in sorted(groups.items(), key=lambda item: tuple(part.casefold() for part in item[0])):
            key = 'FINAL_TARGET_FILES["canonical-gpu"]' + ''.join('[' + json.dumps(part) + ']' for part in parents)
            lines.append(key + ' += [')
            lines.extend('    ' + json.dumps(relative) + ',' for relative in files)
            lines.append(']')
        (staged / 'resources.mozbuild').write_text('\n'.join(lines) + '\n')
        (staged / 'moz.build').write_text('DIST_SUBDIR = ""\n\nif CONFIG["MOZ_WIDGET_TOOLKIT"] == "cocoa":\n    include("resources.mozbuild")\n')
        if target.is_symlink():
            raise ValueError('GPU staging target must not be a symlink')
        if target.exists():
            shutil.rmtree(target)
        staged.rename(target)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path, required=True)
    parser.add_argument('--target', type=Path, required=True)
    args = parser.parse_args()
    stage(args.bundle, args.target)
