"""Verify and stage the exact font inventory, refreshing only our moz.build block."""
from pathlib import Path,PurePosixPath
import argparse,hashlib,json,re,shutil
BEGIN='# Cloakfox: BEGIN managed bundled font resources.'
END='# Cloakfox: END managed bundled font resources.'
def stage(bundle:Path,target:Path):
 data=json.loads((bundle/'font-manifest.json').read_text())
 if data.get('version')!=1:raise ValueError('Unsupported font manifest version')
 records=data['fonts']+data['licenses']+data['notices'];files={}
 actual={str(p.relative_to(bundle))for p in (bundle/'macos').glob('*.ttf')}
 if actual!={x['file']for x in data['fonts']}:raise ValueError('Font inventory differs from manifest')
 for record in records:
  rel=PurePosixPath(record['file']);path=bundle/str(rel)
  if rel.is_absolute()or'..'in rel.parts or not path.is_file() or path.is_symlink()or not path.resolve().is_relative_to(bundle.resolve()):raise ValueError(f'Invalid resource path: {rel}')
  if not re.fullmatch(r'[A-Za-z0-9._-]+',rel.name)or rel.name in files:raise ValueError(f'Invalid/duplicate resource name: {rel.name}')
  if hashlib.sha256(path.read_bytes()).hexdigest()!=record['sha256']:raise ValueError(f'Font resource hash mismatch: {rel}')
  files[rel.name]=path
 files['font-manifest.json']=bundle/'font-manifest.json'
 target.mkdir(parents=True,exist_ok=True);moz=target/'moz.build';text=moz.read_text()if moz.exists()else''
 text=re.sub(r'\n?'+re.escape(BEGIN)+r'\n.*?'+re.escape(END)+r'\n?', '\n',text,flags=re.S)
 # Migrate only the exact legacy blocks generated by copy-additions.sh.
 for label,dist in [('bundled font license notices.',False),('bundled open-substitute font pack (all platforms).',True)]:
  pattern=r'\n?# Cloakfox: '+re.escape(label)+r'\n'+(r'DIST_SUBDIR = ""\n'if dist else'')+r'FINAL_TARGET_FILES.fonts \+= \[\n(?:    "[^"\n]+",\n)*\]\n?'
  text=re.sub(pattern,'\n',text)
 block='\n'+BEGIN+'\nDIST_SUBDIR = ""\nFINAL_TARGET_FILES.fonts += [\n'+''.join('    '+json.dumps(n)+',\n'for n in sorted(files,key=str.lower))+']\n'+END+'\n'
 for name,path in files.items():shutil.copyfile(path,target/name)
 moz.write_text(text.rstrip()+'\n'+block)
 print(f'Staged {len(data["fonts"])} verified fonts and their exact license inventory')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--bundle',type=Path,required=True);p.add_argument('--target',type=Path,required=True);a=p.parse_args();stage(a.bundle,a.target)
