#!/usr/bin/env python3
"""Build the desktop fpgen projection from the reviewed, local model archive.

No fpgen import or network access. Python/zstandard are offline build tools only.
The full byte-identical archive remains packaged as reference/generation data.
"""
import argparse
import copy
import json
import math
from pathlib import Path

from reference_gpu_import import SOURCE, _Values, _bounded_archive, _json, _digest

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "additions/browser/components/cloakfox"
TARGETS = ("navigator.userAgent", "screen", "window", "gpu", "navigator.hardwareConcurrency")


def validate_network(network):
    """Validate all source CPTs, including reference-only nodes, without execution."""
    if not isinstance(network, dict) or not isinstance(network.get("nodes"), list):
        raise ValueError("invalid network")
    nodes = {}
    for node in network["nodes"]:
        name = node["name"]
        if not isinstance(name, str) or name in nodes:
            raise ValueError("duplicate or invalid node name")
        parents = node["parentNames"]
        if not isinstance(parents, list) or len(parents) != len(set(parents)) or any(p not in nodes for p in parents):
            raise ValueError("invalid dependency order")
        possible = node["possibleValues"]
        if not isinstance(possible, list) or not possible or not all(isinstance(p, str) for p in possible) or len(possible) != len(set(possible)):
            raise ValueError("invalid possible values")

        def walk(branch, depth):
            if not isinstance(branch, dict) or not branch:
                raise ValueError("empty conditional branch")
            allowed = nodes[parents[depth]]["possibleValues"] if depth < len(parents) else possible
            if not set(branch) <= set(allowed):
                raise ValueError("conditional token outside node possibilities")
            if depth < len(parents):
                for child in branch.values():
                    walk(child, depth + 1)
            else:
                for weight in branch.values():
                    if type(weight) not in (int, float) or not math.isfinite(weight) or not 0 < weight <= 1:
                        raise ValueError("invalid conditional probability")
                if not math.isclose(sum(branch.values()), 1.0, abs_tol=1e-8):
                    raise ValueError("conditional probabilities do not sum to one")

        walk(node["conditionalProbabilities"], 0)
        nodes[name] = node
    return nodes


def generate(archive):
    pin = _json(SOURCE.read_bytes())
    blobs = _bounded_archive(Path(archive), pin)
    values = _Values(_json(blobs["values.json"]), blobs["values.dat"])
    network = _json(blobs["fingerprint-network.json"])
    nodes = validate_network(network)
    selected = set()

    def include(name):
        if name not in nodes:
            raise ValueError("missing required fpgen node " + name)
        if name in selected:
            return
        selected.add(name)
        for parent in nodes[name]["parentNames"]:
            include(parent)

    for name in TARGETS:
        include(name)
    projection = [node for node in network["nodes"] if node["name"] in selected]
    # Retain every possible value and CPT from selected nodes. No beam truncation,
    # renderer shortlist, row subsampling, or weighting changes in the importer.
    tokens = sorted({token for node in projection for token in node["possibleValues"]})
    decoded = {token: values.get(token) for token in tokens}
    incomplete_windows = []
    orientation_cpt = nodes["matchMedia.mediaCss.orientation"]["conditionalProbabilities"]
    window_cpt = nodes["window"]["conditionalProbabilities"]
    for browser, platforms in orientation_cpt.items():
        for platform, screens in platforms.items():
            for screen, orientations in screens.items():
                for orientation in orientations:
                    if not window_cpt.get(browser, {}).get(platform, {}).get(screen, {}).get(orientation):
                        incomplete_windows.append({"browser": decoded[browser], "platformInfo": decoded[platform],
                                                   "screen": decoded[screen], "orientation": decoded[orientation]})
    data = {"schemaVersion": 1, "sourceArchiveSHA256": pin["archive"]["sha256"], "nodes": projection, "values": decoded}
    encoded = json.dumps(data, separators=(",", ":"), ensure_ascii=True, allow_nan=False)
    module = ("// Generated by scripts/generate-fpgen-network.py; do not edit.\n"
              "// Modified projection of Scrapfly Fingerprint Generator, Apache-2.0.\n"
              "// See fpgen-model-source.json and fpgen-model-LICENSE.txt.\n"
              "// Only model data is shared; container samples are never retained here.\n"
              "function freeze(value) {\n"
              "  if (value && typeof value === 'object' && !Object.isFrozen(value)) {\n"
              "    for (const child of Object.values(value)) freeze(child);\n"
              "    Object.freeze(value);\n"
              "  }\n"
              "  return value;\n"
              "}\n"
              "export const FPGEN_NETWORK = freeze(JSON.parse(" + json.dumps(encoded) + "));\n").encode()
    provenance = copy.deepcopy(pin)
    provenance.update({
        "sourceNodeCount": len(nodes), "sourceValueCount": len(values.entries),
        "packagedReference": "fpgen-model-reference.zip",
        "projectionModule": "CloakfoxFPGenNetwork.sys.mjs",
        "projectionSHA256": _digest(module),
        "projectionNodes": [node["name"] for node in projection],
        "projectionValueCount": len(decoded),
        "incompleteWindowPaths": incomplete_windows,
        "adapterOutputs": ["userAgent", "hardwareConcurrency", "screen", "videoCard"],
        "modifications": [
            "Complete original model archive preserved byte-for-byte as packaged reference data.",
            "Ancestor-closed desktop projection preserves every selected node, value and conditional probability.",
            "Runtime samples browser/platform/GPU jointly with selected OS/hardware constraints; unsupported combinations throw.",
            "Incomplete descendant paths remain in reference/projection data, but sampling conditions on complete paths using their probability mass; there is no uniform fallback.",
            "Browser version is validated presentation metadata normalized by Cloakfox, not a claim of source-version observation.",
            "Screen/window values are allowlisted and geometry normalized by the existing persona mapper.",
            "Recorded GPU labels are observational inputs only; executable capabilities require the existing native admission path.",
            "Permissions, device identifiers, location, languages, fonts, audio, feature availability, WebRTC, TLS and HTTP observations are reference only and never adapter policy."
        ]})
    return {"CloakfoxFPGenNetwork.sys.mjs": module,
            "fpgen-model-source.json": (json.dumps(provenance, indent=2, ensure_ascii=True) + "\n").encode(),
            "fpgen-model-reference.zip": Path(archive).read_bytes(),
            "fpgen-model-LICENSE.txt": pin["license"]["text"].encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generate(args.archive).items():
        target = OUTPUT / name
        if args.check:
            if not target.exists() or target.read_bytes() != content:
                raise SystemExit("generated fpgen artifact differs: " + name)
        else:
            target.write_bytes(content)
        print(("checked " if args.check else "wrote ") + name + " (" + str(len(content)) + " bytes)")


if __name__ == "__main__":
    main()
