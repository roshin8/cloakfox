export function browserValues(profile) {
  const ua = profile.userAgent;
  const oscpu = profile.oscpu || (/Windows NT/.test(ua) ? "Windows NT 10.0; Win64; x64"
    : /Android/.test(ua) ? "Linux armv8l"
    : /Linux/.test(ua) ? "Linux x86_64"
    : /(?:Macintosh|iPhone|iPad)/.test(ua) ? "Intel Mac OS X 10.15" : profile.platform);
  return {"navigator.userAgent": ua, "headers.User-Agent": ua,
    "navigator.appVersion": profile.appVersion, "navigator.platform": profile.platform,
    "navigator.oscpu": oscpu};
}

export function screenValues(profile, current = {}) {
  const values = {"screen.width": profile.width, "screen.height": profile.height,
    "screen.availWidth": profile.availWidth, "screen.availHeight": profile.availHeight,
    "screen.availLeft": 0, "screen.availTop": 0, "window.devicePixelRatio": profile.devicePixelRatio,
    "screen:orientation:type": profile.width >= profile.height ? "landscape-primary" : "portrait-primary"};
  // Retain the existing window size when it fits; constrain it to the new display.
  for (const axis of ["Width", "Height"]) {
    const limit = profile[`avail${axis}`];
    const outer = Math.min(Number(current[`window.outer${axis}`]) || limit, limit);
    values[`window.outer${axis}`] = outer;
    values[`window.inner${axis}`] = Math.min(Number(current[`window.inner${axis}`]) || outer, outer);
  }
  values["window.screenX"] = 0;
  values["window.screenY"] = 0;
  return values;
}

export function languageValues(profile) {
  const locale = new Intl.Locale(profile.id).maximize();
  return {"navigator.language": profile.id,
    "headers.Accept-Language": profile.value.map((lang, i) => i ? `${lang};q=${(1-i*0.1).toFixed(1)}` : lang).join(","),
    "locale:language": locale.language, "locale:region": locale.region, "locale:script": locale.script};
}

export function gpuValues(profile) {
  return {"webGl:vendor": profile.vendor, "webGl:renderer": profile.renderer};
}
